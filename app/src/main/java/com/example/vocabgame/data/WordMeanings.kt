    fun hasMeaning(word: String): Boolean = meaningsMap.containsKey(word.trim().uppercase(Locale.US))

    fun getMeaning(word: String): String {
        val upper = word.trim().uppercase(Locale.US)
        
        // 1. Direct dictionary match
        val direct = meaningsMap[upper]
        if (direct != null) return direct

        // 2. Plural form (e.g. CATS -> Plural form of cat)
        if (upper.endsWith("S") && upper.length > 2) {
            val root = upper.dropLast(1)
            val rootMeaning = meaningsMap[root]
            if (rootMeaning != null) {
                return "Plural form of ${root.lowercase(Locale.US)}: $rootMeaning"
            }
        }

        // 3. Past tense form (e.g. COOKED/TIED)
        if (upper.endsWith("D") && upper.length > 2) {
            val root = upper.dropLast(1)
            val rootMeaning = meaningsMap[root]
            if (rootMeaning != null) {
                return "Past tense form of ${root.lowercase(Locale.US)}: $rootMeaning"
            }
        }

        // 4. Agent / Comparative form (e.g. BAKER)
        if (upper.endsWith("R") && upper.length > 2) {
            val root = upper.dropLast(1)
            val rootMeaning = meaningsMap[root]
            if (rootMeaning != null) {
                return "Agent or comparative form of ${root.lowercase(Locale.US)}: $rootMeaning"
            }
        }

        // 5. Intelligent linguistic fallback
        val vowels = upper.count { it in "AEIOU" }
        return "A meaningful four-letter English vocabulary term ('$upper'), containing $vowels vowel sound${if (vowels != 1) "s" else ""}."
    }
